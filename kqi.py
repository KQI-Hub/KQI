VER = "0.0.0"

from datetime import datetime, timezone # for KQI timestamping

import mcv
from ycocg import rgb_to_ycocg_r, ycocg_r_to_rgb
from haar import haar_on_plane, unhaar_plane
from chunking import bitmap_to_chunkmap, chunkmap_to_bitmap, flat_bitmap_to_chunkmap
from huffman import huffman_enc, huffman_dec
from scqoi2 import compress, decompress
from ppmgen import get_alpha, gal_pack

def kqi_haar_plane(channel, img_w, img_h, img_hw, img_hh):
    chunked_image = bitmap_to_chunkmap(channel)
    s, h, v, d = haar_on_plane(chunked_image, img_w, img_h)
    chunked_s = flat_bitmap_to_chunkmap(s, img_hw, img_hh)
    ss, sh, sv, sd = haar_on_plane(chunked_s, img_hw, img_hh)
    return ss, sh, sv, sd, h, v, d

def flatten(lst):
    out = []
    for item in lst:
        out.extend(item)
    return out

def make_text_chunk(ctype: str, cdata: str):
    if len(ctype) != 1:
        raise ValueError("Chunk Type must be exactly 1!")
    chk = bytearray(f't{ctype}'.encode('ascii'))

    cdata = cdata.encode('utf-8') # processes the cdata

    chk.extend(len(cdata).to_bytes(6, 'little'))
    chk.extend(cdata)
    return chk

def make_subband_chunk(ctype: str, plane: bytes, subband: int):
    if len(ctype) != 1:
        raise ValueError("Chunk Type must be exactly 1!")
    chk = bytearray(f's{ctype}'.encode('ascii'))

    cdata = bytearray([subband]) # 0 is sum-sum, 1 is sum-hdiff, 2 is sum-vdiff, 3 is sum-diag, 4 is hdiff, 5 is vdiff, and 6 is diag
    scq2plane = compress(plane, do_diff=False) # scQOI2 compression
    huffcoded = huffman_enc(scq2plane) # Huffman coding
    cdata.extend(huffcoded)

    chk.extend(len(cdata).to_bytes(6, 'little'))
    chk.extend(cdata)
    return chk

def make_alpha_chunk(ctype: str, plane: bytes):
    if len(ctype) != 1:
        raise ValueError("Chunk Type must be exactly 1!")
    chk = bytearray(f'a{ctype}'.encode('ascii'))

    plane = bytes(flatten(plane))

    scq2plane = compress(plane, do_diff=False) # scQOI2 compression
    cdata = huffman_enc(scq2plane) # Huffman coding

    chk.extend(len(cdata).to_bytes(6, 'little'))
    chk.extend(cdata)
    return chk

def encode(src_img, *, alpha = True, subsample = False):
    bits = bytearray(b'kqif') # kqif header bytes 0-3
    # get dimensions
    img_w = len(src_img[0])
    img_h = len(src_img)
    img_hw, img_hh = (img_w+1)//2, (img_h+1)//2
    if subsample:
        cimg_w, cimg_h = img_hw, img_hh
        cimg_hw, cimg_hh = (img_hw+1)//2, (img_hh+1)//2
    else:
        cimg_w, cimg_h, cimg_hw, cimg_hh = img_w, img_h, img_hw, img_hh

    bits.extend(img_w.to_bytes(4, 'little')) # width, bytes 4-7
    bits.extend(img_h.to_bytes(4, 'little')) # height, bytes 8-11

    grayscale = False
    if type(src_img[0][0]) == int:
        grayscale = True
        if alpha is True:
            alpha = False

    img_a = None
    if alpha is True:
        img_a = get_alpha(src_img)
    elif type(alpha) is list:
        img_a = alpha
    if not img_a:
        alpha = False # disable alpha if it doesnt exist

    channels = 3
    if alpha:
         channels +=1
    if grayscale:
         channels -=2
    bits.append(channels) # channels count, byte 12

    bits.append(0) # colorspace, 0=sRGB+lA; 1=lRGBA; 2=ICC Chunk, byte 13
    bits.append(int(subsample)) # subsampling mode, 0=4:4:4, 1=4:2:0; byte 14
    bits.append(0) # reserved/padding, byte 15

    bits.extend(make_text_chunk("C", datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")))
    bits.extend(make_text_chunk("E", mcv.save({"name":"kmi","version:":VER,"build_date":"","params":"","input_fn":"","output_fn":""}, comment="file generated by KQI Model for Images (KMI)"))) # add encoder info
    bits.extend(make_text_chunk("X", "This KQI file was generated by KMI")) # add comment

    # lossy companded YCoCg-R, it is good for colors with low saturation
    if grayscale:
        img_y = src_img
    else:
        img_y, img_co, img_cg = rgb_to_ycocg_r(src_img, subsample=subsample)

    # transform to haar stuffs -- note: please make it support grayscale later
    # yss, ysh, ysv, ysd, yh, yv, yd
    y_sb = kqi_haar_plane(img_y, img_w, img_h, img_hw, img_hh)
    if not grayscale:
        # coss, cosh, cosv, cosd, coh, cov, cod
        co_sb = kqi_haar_plane(img_co, cimg_w, cimg_h, cimg_hw, cimg_hh)
        # cgss, cgsh, cgsv, cgsd, cgh, cgv, cgd
        cg_sb = kqi_haar_plane(img_cg, cimg_w, cimg_h, cimg_hw, cimg_hh)

    if alpha:
        bits.extend(make_alpha_chunk("L", img_a))

    if grayscale:
        for sbt, sby in enumerate(y_sb):
            bits.extend(make_subband_chunk("Y", sby, sbt))
    else:
        for sbt, (sby, sbco, sbcg) in enumerate(zip(y_sb, co_sb, cg_sb)):
            bits.extend(make_subband_chunk("Y", sby, sbt))
            bits.extend(make_subband_chunk("O", sbco, sbt))
            bits.extend(make_subband_chunk("G", sbcg, sbt))

    bits.extend(b'eF') # EoF Marker
    return bits

def decode(kqi_bytes: bytes, *, verbose = False):
    if kqi_bytes[0:4] != b'kqif':
        raise ValueError("Not a KQI Image!")
    img_w = int.from_bytes(kqi_bytes[4:8], "little")
    img_h = int.from_bytes(kqi_bytes[8:12], "little")
    channels = kqi_bytes[12]
    is_subsampled = bool(kqi_bytes[14])
    iscolor = channels > 2

    img_hw, img_hh = (img_w+1)//2, (img_h+1)//2
    y_sb, co_sb, cg_sb = [None]*7, [None]*7, [None]*7
    alph = None

    if is_subsampled:
        cimg_w, cimg_h = img_hw, img_hh
        cimg_hw, cimg_hh = (img_hw+1)//2, (img_hh+1)//2
    else:
        cimg_w, cimg_h, cimg_hw, cimg_hh = img_w, img_h, img_hw, img_hh

    bw = 16 # start at the start of the 1st chunk
    while True:
        TwoCC = kqi_bytes[bw:bw+2]
        if TwoCC == b'eF':
            break
        if len(TwoCC) != 2:
            raise EOFError("Read past end of KQI file, eF marker missed")

        chk_len = int.from_bytes(kqi_bytes[bw+2:bw+8], "little")
        if TwoCC == b'sY':
            sbid = kqi_bytes[bw+8]
            if verbose:
                print('sY chunk found, subband:', sbid, 'length:', chk_len)
            y_sb[sbid] = decompress(huffman_dec(kqi_bytes[bw+9:bw+8+chk_len]))
        elif TwoCC == b'sO':
            sbid = kqi_bytes[bw+8]
            if verbose:
                print('sO chunk found, subband:', sbid, 'length:', chk_len)
            co_sb[sbid] = decompress(huffman_dec(kqi_bytes[bw+9:bw+8+chk_len]))
        elif TwoCC == b'sG':
            sbid = kqi_bytes[bw+8]
            if verbose:
                print('sG chunk found, subband:', sbid, 'length:', chk_len)
            cg_sb[sbid] = decompress(huffman_dec(kqi_bytes[bw+9:bw+8+chk_len]))
        elif TwoCC == b'aL':
            if verbose:
                print('aL chunk found, length:', chk_len)
            alph = decompress(huffman_dec(kqi_bytes[bw+8:bw+8+chk_len]))
        else:
            if verbose:
                print(TwoCC, chk_len) # simply print unknown chunk statistics
        bw+=chk_len+8
    yds = unhaar_plane(y_sb[0], y_sb[1], y_sb[2], y_sb[3])
    yds = flatten(chunkmap_to_bitmap(yds, img_hw, img_hh))
    cdimg = unhaar_plane(yds, y_sb[4], y_sb[5], y_sb[6])
    dimg_y = chunkmap_to_bitmap(cdimg, img_w, img_h)

    if iscolor:
        cods = unhaar_plane(co_sb[0], co_sb[1], co_sb[2], co_sb[3])
        cods = flatten(chunkmap_to_bitmap(cods, cimg_hw, cimg_hh))
        cdimg = unhaar_plane(cods, co_sb[4], co_sb[5], co_sb[6])
        dimg_co = chunkmap_to_bitmap(cdimg, cimg_w, cimg_h)

        cgds = unhaar_plane(cg_sb[0], cg_sb[1], cg_sb[2], cg_sb[3])
        cgds = flatten(chunkmap_to_bitmap(cgds, cimg_hw, cimg_hh))
        cdimg = unhaar_plane(cgds, cg_sb[4], cg_sb[5], cg_sb[6])
        dimg_cg = chunkmap_to_bitmap(cdimg, cimg_w, cimg_h)

        return ycocg_r_to_rgb(dimg_y, dimg_co, dimg_cg, alph, subsampled=is_subsampled)
    elif channels == 2:
        return gal_pack(dimg_y, alph)
    else:
        return dimg_y

